CREATE TABLE invoices (id INTEGER PRIMARY KEY, customer_id INTEGER REFERENCES customers (id) ON DELETE CASCADE, total INTEGER, paid INTEGER DEFAULT 0, FOREIGN KEY (customer_id) REFERENCES customers);
CREATE INDEX invoices_unpaid ON invoices (customer_id) WHERE paid = 0;
CREATE INDEX customers_email ON customers (lower(email));
CREATE VIEW customer_totals AS SELECT c.id, c.email, sum(i.total) AS total FROM customers c LEFT JOIN invoices i ON i.customer_id = c.id GROUP BY c.id;
